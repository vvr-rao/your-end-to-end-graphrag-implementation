#!/usr/bin/env python3
"""Save YEGI datasets to a PRIVATE Hugging Face dataset repo, and download them back.

Optional step. Nothing here runs unless you call it, and the app never needs it.

What it uploads (you choose each one explicitly):

  --corpus DIR|FILE   unstructured documents, e.g. source_documents/pharma-12-audit
  --structured DIR    output of structured_download.py (every snapshot folder with
                      a manifest.json under DIR), e.g. source_documents/structured_sec
  --eval DIR|FILE     evaluation questions / test sets / eval outputs, e.g.
                      eval_questions or eval_questions/testsets/pharma12.json

Repo layout (one ``yegi_manifest.json`` at the top records every item, its files,
SHA-256s and where ``pull`` restores it):

  unstructured/<corpus>/...             -> source_documents/<corpus>/...
  structured/<source>/<dataset>/<snap>/ -> source_documents/structured_<source>/<dataset>/<snap>/
  eval/<name>/...                       -> eval_questions/... (same path it came from)

Items keep the repo-relative path they had locally, so a test set's
``"corpus": "source_documents/pharma-12-audit"`` still resolves after ``pull``.

Privacy: ``push`` creates the repo as PRIVATE and refuses to write to a repo that
is not private. The token comes only from ``HF_TOKEN`` (``.env``) and is never
printed. Files named ``.env*``, keys, ``.part``/``.bak`` leftovers and caches are
never uploaded.

Usage (from the repo root; needs ``uv sync --extra hf``):

    uv run python source_documents/hf_dataset.py whoami
    uv run python source_documents/hf_dataset.py push --repo yegi-pharma \\
        --corpus source_documents/pharma-12-audit \\
        --eval eval_questions/testsets/pharma12.json --dry-run
    uv run python source_documents/hf_dataset.py list --repo <user>/yegi-pharma
    uv run python source_documents/hf_dataset.py pull --repo <user>/yegi-pharma
"""

from __future__ import annotations

import argparse
import fnmatch
import hashlib
import json
import os
import shutil
import socket
import sys
from collections.abc import Callable, Iterable, Iterator
from contextlib import contextmanager
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path, PurePosixPath
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
TOKEN_ENV = "HF_TOKEN"
MANIFEST_NAME = "yegi_manifest.json"
CARD_NAME = "README.md"
FORMAT = "yegi-hf-dataset/1"
CARD_MARKER = "<!-- yegi-hf-dataset: generated by source_documents/hf_dataset.py -->"
STAGING_DIR = ".hf_staging"
KINDS = ("unstructured", "structured", "eval")

# Never uploaded, wherever they sit inside a selected folder.
EXCLUDED_DIRS = {"__pycache__", ".git", ".hf_staging", ".cache", ".ipynb_checkpoints"}
EXCLUDED_NAMES = {".DS_Store", "Thumbs.db", "desktop.ini"}
EXCLUDED_SUFFIXES = (".part", ".pyc", ".bak", ".tmp", ".swp", ".pem", ".key", ".p12")
EXCLUDED_GLOBS = (".env", ".env.*", "*credentials*", "*secret*", "id_rsa*")

MAX_FILES_PER_COMMIT = 200
MAX_BYTES_PER_COMMIT = 2 << 30


class UsageError(Exception):
    """Bad arguments or an unsafe request: exit code 2."""


# --------------------------------------------------------------------- helpers


def log(msg: str) -> None:
    print(msg, file=sys.stderr)


def human(n: float) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.1f} GB"  # pragma: no cover


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def load_env() -> None:
    try:
        from dotenv import load_dotenv
    except ImportError:  # pragma: no cover
        return
    env = REPO_ROOT / ".env"
    if env.exists():
        load_dotenv(env, override=False)


def get_token(required: bool) -> str | None:
    token = os.environ.get(TOKEN_ENV, "").strip() or None
    if required and not token:
        raise UsageError(
            f"{TOKEN_ENV} is not set. Create a token at https://huggingface.co/settings/tokens "
            f"(a 'write' token for push, 'read' is enough for pull) and add "
            f"{TOKEN_ENV}=... to .env. Never paste it into a command line or chat.")
    return token


def excluded_reason(rel: PurePosixPath) -> str | None:
    """Why a file must not be uploaded, or None if it is fine."""
    for part in rel.parts[:-1]:
        if part in EXCLUDED_DIRS:
            return f"inside {part}/"
    name = rel.name
    if name in EXCLUDED_NAMES:
        return "OS metadata file"
    if name.lower().endswith(EXCLUDED_SUFFIXES):
        return "temporary/backup/key file"
    for pat in EXCLUDED_GLOBS:
        if fnmatch.fnmatch(name.lower(), pat):
            return "may contain credentials"
    return None


def safe_rel(text: str) -> PurePosixPath:
    """Validate a repo-relative path that came from a (possibly untrusted) manifest."""
    p = PurePosixPath(text)
    if not text or p.is_absolute() or ".." in p.parts or "\\" in text or ":" in p.parts[0]:
        raise UsageError(f"unsafe path in remote manifest: {text!r}")
    return p


def inside(child: Path, parent: Path) -> bool:
    try:
        child.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


def repo_relative(path: Path) -> str | None:
    """Path relative to the repo root (posix), or None if outside it."""
    try:
        return path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return None


# ----------------------------------------------------------------- local items


@dataclass
class FileEntry:
    rel: str                 # path inside the item (posix)
    bytes: int
    sha256: str
    local: Path | None = None  # set for local files only


@dataclass
class Item:
    kind: str
    name: str
    repo_prefix: str          # folder (or file path) inside the HF repo
    restore_to: str           # repo-root-relative path pull writes to
    is_file: bool = False     # a single file rather than a folder
    files: list[FileEntry] = field(default_factory=list)
    meta: dict[str, Any] = field(default_factory=dict)

    def repo_path(self, f: FileEntry) -> str:
        return self.repo_prefix if self.is_file else f"{self.repo_prefix}/{f.rel}"

    def total_bytes(self) -> int:
        return sum(f.bytes for f in self.files)

    def to_dict(self) -> dict[str, Any]:
        return {"kind": self.kind, "name": self.name, "repo_prefix": self.repo_prefix,
                "restore_to": self.restore_to, "is_file": self.is_file,
                "file_count": len(self.files), "bytes": self.total_bytes(),
                "files": [{"path": f.rel, "bytes": f.bytes, "sha256": f.sha256}
                          for f in sorted(self.files, key=lambda f: f.rel)],
                **({"meta": self.meta} if self.meta else {})}

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Item:
        kind = d.get("kind")
        if kind not in KINDS:
            raise UsageError(f"unknown item kind in remote manifest: {kind!r}")
        item = cls(kind=kind, name=str(d["name"]), repo_prefix=str(safe_rel(d["repo_prefix"])),
                   restore_to=str(safe_rel(d["restore_to"])), is_file=bool(d.get("is_file")),
                   meta=dict(d.get("meta") or {}))
        for f in d.get("files", []):
            rel = f["path"] if item.is_file else str(safe_rel(f["path"]))
            item.files.append(FileEntry(rel=rel, bytes=int(f["bytes"]), sha256=str(f["sha256"])))
        return item


def _link_target(p: Path) -> tuple[Path | None, str]:
    """Resolve a symlinked file. Subset corpora (e.g. pharma-12-audit) are folders of
    links into a larger corpus, so links to regular files INSIDE the repo are
    followed; anything else (outside the repo, broken, a folder) is skipped."""
    try:
        target = p.resolve(strict=True)
    except (OSError, RuntimeError):
        return None, "broken symlink"
    if not target.is_file():
        return None, "symlink to a folder (not followed)"
    if not inside(target, REPO_ROOT):
        return None, "symlink to a file outside the repo (not followed)"
    why = excluded_reason(PurePosixPath(target.name))
    if why:
        return None, f"symlink target {why}"
    return target, ""


def _scan(root: Path, skipped: list[str], *, skip_names: Iterable[str] = ()) -> list[FileEntry]:
    skip = set(skip_names)
    out: list[FileEntry] = []
    for p in sorted(root.rglob("*")):
        source = p
        if p.is_symlink():
            target, why = _link_target(p)
            if target is None:
                skipped.append(f"{p} ({why})")
                continue
            source = target
        elif not p.is_file():
            continue
        rel = PurePosixPath(p.relative_to(root).as_posix())
        if rel.as_posix() in skip:
            continue
        why = excluded_reason(rel)
        if why:
            skipped.append(f"{p} ({why})")
            continue
        out.append(FileEntry(rel=rel.as_posix(), bytes=source.stat().st_size, sha256="",
                             local=source))
    return out


def _single(path: Path, skipped: list[str]) -> list[FileEntry]:
    why = excluded_reason(PurePosixPath(path.name))
    if why:
        raise UsageError(f"refusing to upload {path}: {why}")
    source = path
    if path.is_symlink():
        target, why = _link_target(path)
        if target is None:
            raise UsageError(f"refusing to upload {path}: {why}")
        source = target
    return [FileEntry(rel=path.name, bytes=source.stat().st_size, sha256="", local=source)]


def collect_corpus(path: Path, skipped: list[str]) -> Item:
    if not path.exists():
        raise UsageError(f"--corpus not found: {path}")
    rel = repo_relative(path)
    restore = rel if rel else f"source_documents/{path.name}"
    if path.is_file():
        return Item("unstructured", path.name, f"unstructured/{path.name}", restore,
                    is_file=True, files=_single(path, skipped))
    files = _scan(path, skipped)
    if not files:
        raise UsageError(f"--corpus {path} has no files to upload")
    return Item("unstructured", path.name, f"unstructured/{path.name}", restore, files=files)


def collect_structured(path: Path, skipped: list[str], *, include_failed: bool) -> list[Item]:
    if not path.is_dir():
        raise UsageError(f"--structured must be a folder written by structured_download.py: {path}")
    manifests = sorted(path.rglob("manifest.json"))
    if not manifests:
        raise UsageError(f"--structured {path}: no manifest.json found (is this a "
                         f"structured_download.py output folder?)")
    items: list[Item] = []
    for mpath in manifests:
        snap = mpath.parent
        if any(inside(snap, it_root) for it_root in (Path(i.meta["_root"]) for i in items)):
            continue  # a manifest nested inside another snapshot: part of that one
        try:
            m = json.loads(mpath.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as e:
            raise UsageError(f"cannot read {mpath}: {e}") from e
        source, dataset = str(m.get("source") or ""), str(m.get("dataset") or "")
        if not source or not dataset:
            raise UsageError(f"{mpath} has no source/dataset; not a structured_download manifest")
        status = m.get("status")
        if status == "failed" and not include_failed:
            skipped.append(f"{snap} (manifest status failed; pass --include-failed to upload)")
            continue
        name = f"{source}/{dataset}/{snap.name}"
        files = _scan(snap, skipped)
        meta = {"_root": str(snap), "status": status, "snapshot_kind": m.get("snapshot_kind"),
                "source_release": m.get("source_release"), "retrieved_at": m.get("retrieved_at"),
                "attribution": m.get("attribution"), "terms_urls": m.get("terms_urls") or []}
        # Inside the checkout: restore exactly where it was pushed from (e.g. a
        # hand-assembled source_documents/<bundle>/sec/...). Outside it: the
        # downloader's default layout.
        restore = repo_relative(snap) or f"source_documents/structured_{source}/{dataset}/{snap.name}"
        items.append(Item("structured", name, f"structured/{name}", restore,
                          files=files, meta=meta))
    for it in items:
        it.meta.pop("_root", None)
        it.meta = {k: v for k, v in it.meta.items() if v not in (None, [], "")}
    return items


def collect_eval(path: Path, skipped: list[str]) -> Item:
    if not path.exists():
        raise UsageError(f"--eval not found: {path}")
    rel = repo_relative(path)
    restore = rel if rel else f"eval_questions/{path.name}"
    prefix = f"eval/{rel if rel and rel.startswith('eval_questions') else path.name}"
    if path.is_file():
        return Item("eval", path.name, prefix, restore, is_file=True, files=_single(path, skipped))
    files = _scan(path, skipped)
    if not files:
        raise UsageError(f"--eval {path} has no files to upload")
    return Item("eval", rel or path.name, prefix, restore, files=files)


def hash_items(items: list[Item]) -> None:
    for it in items:
        for f in it.files:
            if f.local is not None and not f.sha256:
                f.sha256 = sha256_file(f.local)


def check_unique(items: list[Item]) -> None:
    seen: dict[str, str] = {}
    for it in items:
        for f in it.files:
            rp = it.repo_path(f)
            if rp in seen:
                raise UsageError(f"two selections map to the same repo path {rp!r} "
                                 f"({seen[rp]} and {it.name}); rename one folder")
            seen[rp] = it.name
        if it.repo_prefix in (MANIFEST_NAME, CARD_NAME):
            raise UsageError(f"{it.name}: reserved repo path {it.repo_prefix}")


# ------------------------------------------------------------------ manifest


def new_manifest(repo_id: str) -> dict[str, Any]:
    return {"format": FORMAT, "repo_id": repo_id, "items": []}


def merge_manifest(prior: dict[str, Any], items: list[Item], *, repo_id: str,
                   pushed_at: str, kept_stale: dict[str, list[FileEntry]]) -> dict[str, Any]:
    """Replace the entries of re-pushed items (same repo_prefix), keep the others."""
    by_prefix = {d["repo_prefix"]: d for d in prior.get("items", [])}
    for it in items:
        d = it.to_dict()
        stale = kept_stale.get(it.repo_prefix, [])
        if stale:  # remote files no longer present locally and not deleted
            d["files"] = sorted(d["files"] + [{"path": f.rel, "bytes": f.bytes, "sha256": f.sha256}
                                              for f in stale], key=lambda x: x["path"])
            d["file_count"] = len(d["files"])
            d["bytes"] = sum(x["bytes"] for x in d["files"])
        d["pushed_at"] = pushed_at
        by_prefix[it.repo_prefix] = d
    return {"format": FORMAT, "repo_id": repo_id, "updated_at": pushed_at,
            "items": sorted(by_prefix.values(), key=lambda d: (d["kind"], d["repo_prefix"]))}


def render_card(manifest: dict[str, Any]) -> str:
    rows, terms = [], []
    for d in manifest["items"]:
        rows.append(f"| {d['kind']} | `{d['name']}` | {d['file_count']} | {human(d['bytes'])} "
                    f"| `{d['restore_to']}` | {d.get('pushed_at', '')[:10]} |")
        meta = d.get("meta") or {}
        if meta.get("attribution") or meta.get("terms_urls"):
            urls = ", ".join(meta.get("terms_urls") or [])
            terms.append(f"- `{d['name']}`: {meta.get('attribution') or ''} {urls}".rstrip())
    lines = [
        "---", "viewer: false", "tags:", "- yegi", "- graphrag", "---", "", CARD_MARKER, "",
        f"# {manifest['repo_id']}", "",
        "Private dataset of YEGI source material: unstructured documents, structured "
        "downloads and evaluation sets. Written by `source_documents/hf_dataset.py`; "
        f"`{MANIFEST_NAME}` lists every file with its SHA-256 and where `pull` restores it.",
        "", "Restore into a YEGI checkout:", "", "```",
        f"uv run python source_documents/hf_dataset.py pull --repo {manifest['repo_id']}", "```",
        "", "| kind | item | files | size | restores to | pushed |",
        "|---|---|---:|---:|---|---|", *rows, "",
        "## Third-party data", "",
        "Contents come from third-party publishers and keep their original terms. "
        "This repo must stay private unless every source's licence allows redistribution.",
    ]
    if terms:
        lines += ["", *terms]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ HF access


def make_api(token: str | None) -> Any:
    try:
        from huggingface_hub import HfApi
    except ImportError as e:
        raise UsageError("huggingface_hub is not installed: run `uv sync --extra hf`") from e
    return HfApi(token=token)


def _is_not_found(exc: Exception) -> bool:
    name = type(exc).__name__
    return name in {"RepositoryNotFoundError", "RemoteEntryNotFoundError",
                    "EntryNotFoundError", "RevisionNotFoundError"} or \
        getattr(getattr(exc, "response", None), "status_code", None) == 404


def resolve_repo_id(api: Any, repo: str) -> str:
    if "/" in repo:
        return repo
    user = api.whoami()["name"]
    return f"{user}/{repo}"


def ensure_private_repo(api: Any, repo_id: str, *, create: bool) -> bool:
    """Return True if the repo exists (or was created). Refuse anything not private."""
    try:
        info = api.repo_info(repo_id, repo_type="dataset")
    except Exception as e:
        if not _is_not_found(e):
            raise
        if not create:
            return False
        api.create_repo(repo_id, repo_type="dataset", private=True)
        info = api.repo_info(repo_id, repo_type="dataset")
        log(f"created PRIVATE dataset repo {repo_id}")
    if info.private is not True:
        raise UsageError(f"{repo_id} is not private; this tool only writes to private repos. "
                         f"Make it private on huggingface.co or choose another --repo.")
    return True


def fetch_remote_manifest(api: Any, repo_id: str, revision: str | None = None) -> dict | None:
    try:
        path = api.hf_hub_download(repo_id, MANIFEST_NAME, repo_type="dataset", revision=revision)
    except Exception as e:
        if _is_not_found(e):
            return None
        raise
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if data.get("format") != FORMAT:
        raise UsageError(f"{repo_id}/{MANIFEST_NAME} has format {data.get('format')!r}; "
                         f"expected {FORMAT!r}")
    return data


def fetch_remote_card(api: Any, repo_id: str) -> str | None:
    try:
        return Path(api.hf_hub_download(repo_id, CARD_NAME, repo_type="dataset")).read_text(
            encoding="utf-8")
    except Exception as e:
        if _is_not_found(e):
            return None
        raise


# ---------------------------------------------------------------------- push


def batched(ops: list[tuple[str, FileEntry]]) -> Iterable[list[tuple[str, FileEntry]]]:
    batch: list[tuple[str, FileEntry]] = []
    size = 0
    for op in ops:
        if batch and (len(batch) >= MAX_FILES_PER_COMMIT or size + op[1].bytes > MAX_BYTES_PER_COMMIT):
            yield batch
            batch, size = [], 0
        batch.append(op)
        size += op[1].bytes
    if batch:
        yield batch


def cmd_push(args: argparse.Namespace, api_factory: Callable[[str | None], Any]) -> int:
    if not (args.corpus or args.structured or args.eval):
        raise UsageError("nothing selected: pass at least one --corpus, --structured or --eval")
    skipped: list[str] = []
    items: list[Item] = []
    for p in args.corpus or []:
        items.append(collect_corpus(Path(p), skipped))
    for p in args.structured or []:
        items += collect_structured(Path(p), skipped, include_failed=args.include_failed)
    for p in args.eval or []:
        items.append(collect_eval(Path(p), skipped))
    if not items:
        raise UsageError("nothing to upload after exclusions")
    check_unique(items)
    log(f"hashing {sum(len(i.files) for i in items)} local files ...")
    hash_items(items)

    token = get_token(required=not args.dry_run)
    api = api_factory(token) if token else None
    repo_id = resolve_repo_id(api, args.repo) if api else args.repo
    exists = ensure_private_repo(api, repo_id, create=False) if api else False
    prior = (fetch_remote_manifest(api, repo_id) if exists else None) or new_manifest(repo_id)
    prior_items = {d["repo_prefix"]: Item.from_dict(d) for d in prior.get("items", [])}

    uploads: list[tuple[str, FileEntry]] = []
    deletes: list[str] = []
    kept_stale: dict[str, list[FileEntry]] = {}
    unchanged = 0
    for it in items:
        old = prior_items.get(it.repo_prefix)
        old_sha = {o.rel: o.sha256 for o in old.files} if old else {}
        for f in it.files:
            if not args.force and old_sha.get(f.rel) == f.sha256:
                unchanged += 1
            else:
                uploads.append((it.repo_path(f), f))
        if old:
            local = {f.rel for f in it.files}
            stale = [o for o in old.files if o.rel not in local]
            if stale and args.delete_missing:
                deletes += [old.repo_path(o) for o in stale]
            elif stale:
                kept_stale[it.repo_prefix] = stale

    print(f"repo: {repo_id} (dataset, PRIVATE){'' if exists else '  [will be created]'}"
          f"{'  [remote not checked: no ' + TOKEN_ENV + ']' if not api else ''}")
    for it in items:
        tag = f" status={it.meta['status']}" if it.meta.get("status") else ""
        print(f"  {it.kind:<12} {it.name}  {len(it.files)} files, {human(it.total_bytes())}{tag}"
              f"  -> {it.repo_prefix}  (restores to {it.restore_to})")
    up_bytes = sum(f.bytes for _, f in uploads)
    print(f"upload: {len(uploads)} files, {human(up_bytes)}; unchanged (skipped): {unchanged}; "
          f"delete: {len(deletes)}")
    for prefix, stale in kept_stale.items():
        print(f"  note: {len(stale)} remote file(s) under {prefix} no longer exist locally; kept "
              f"(pass --delete-missing to remove them)")
    if skipped:
        print(f"excluded locally: {len(skipped)} file(s)")
        for s in skipped[:20]:
            print(f"  - {s}")
        if len(skipped) > 20:
            print(f"  ... and {len(skipped) - 20} more")
    if args.dry_run:
        print("dry run: nothing uploaded")
        return 0
    if not uploads and not deletes:
        print("remote already up to date")
        return 0

    from huggingface_hub import CommitOperationAdd, CommitOperationDelete

    ensure_private_repo(api, repo_id, create=True)
    message = args.message or f"hf_dataset push: {', '.join(i.name for i in items)}"[:200]
    batches = list(batched(uploads))
    for n, batch in enumerate(batches, 1):
        log(f"commit {n}/{len(batches)}: {len(batch)} files, {human(sum(f.bytes for _, f in batch))}")
        ops = [CommitOperationAdd(path_in_repo=rp, path_or_fileobj=str(f.local)) for rp, f in batch]
        api.create_commit(repo_id, ops, repo_type="dataset",
                          commit_message=f"{message} ({n}/{len(batches)})")

    pushed_at = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    merged = merge_manifest(prior, items, repo_id=repo_id, pushed_at=pushed_at,
                            kept_stale=kept_stale)
    final = [CommitOperationDelete(path_in_repo=p) for p in deletes]
    final.append(CommitOperationAdd(path_in_repo=MANIFEST_NAME, path_or_fileobj=(
        json.dumps(merged, indent=2, ensure_ascii=False) + "\n").encode("utf-8")))
    card = fetch_remote_card(api, repo_id)
    if card is None or CARD_MARKER in card:
        final.append(CommitOperationAdd(path_in_repo=CARD_NAME,
                                        path_or_fileobj=render_card(merged).encode("utf-8")))
    else:
        log("README.md on the repo was edited by hand; left unchanged")
    api.create_commit(repo_id, final, repo_type="dataset",
                      commit_message=f"{message}: update {MANIFEST_NAME}")
    print(f"pushed {len(uploads)} files to https://huggingface.co/datasets/{repo_id} (private)")
    return 0


# ---------------------------------------------------------------------- list


def cmd_list(args: argparse.Namespace, api_factory: Callable[[str | None], Any]) -> int:
    token = get_token(required=False)
    api = api_factory(token)
    if "/" not in args.repo and not token:
        raise UsageError("give --repo as owner/name (or set HF_TOKEN to use your own account)")
    repo_id = resolve_repo_id(api, args.repo)
    manifest = fetch_remote_manifest(api, repo_id, args.revision)
    if manifest is None:
        files = api.list_repo_files(repo_id, repo_type="dataset", revision=args.revision)
        print(f"{repo_id}: no {MANIFEST_NAME} (not written by this tool); {len(files)} files")
        return 0
    print(f"{repo_id}  (updated {manifest.get('updated_at', '?')})")
    for d in manifest["items"]:
        print(f"  {d['kind']:<12} {d['name']}  {d['file_count']} files, {human(d['bytes'])}"
              f"  -> {d['restore_to']}")
    return 0


# ---------------------------------------------------------------------- pull


def select_items(manifest: dict[str, Any], names: list[str] | None,
                 kinds: list[str] | None) -> list[Item]:
    items = [Item.from_dict(d) for d in manifest.get("items", [])]
    if kinds:
        items = [i for i in items if i.kind in kinds]
    if names:
        wanted = set(names)
        found = [i for i in items if i.name in wanted or i.repo_prefix in wanted]
        missing = wanted - {i.name for i in found} - {i.repo_prefix for i in found}
        if missing:
            raise UsageError(f"not in the dataset: {', '.join(sorted(missing))} "
                             f"(see the `list` command for item names)")
        items = found
    return items


def cmd_pull(args: argparse.Namespace, api_factory: Callable[[str | None], Any]) -> int:
    token = get_token(required=False)
    if "/" not in args.repo and not token:
        raise UsageError("give --repo as owner/name (or set HF_TOKEN to use your own account)")
    api = api_factory(token)
    repo_id = resolve_repo_id(api, args.repo)
    root = Path(args.root).resolve() if args.root else REPO_ROOT
    manifest = fetch_remote_manifest(api, repo_id, args.revision)
    if manifest is None:
        return _pull_raw(api, repo_id, root, args)
    items = select_items(manifest, args.item, args.kind)
    if not items:
        print("nothing selected")
        return 0

    plan: list[tuple[str, Path, FileEntry]] = []
    conflicts, same = [], 0
    for it in items:
        base = root / it.restore_to
        for f in it.files:
            dest = base if it.is_file else base / f.rel
            if not inside(dest, root):
                raise UsageError(f"remote manifest points outside {root}: {it.restore_to}/{f.rel}")
            if dest.exists():
                if dest.is_file() and sha256_file(dest) == f.sha256:
                    same += 1
                    continue
                conflicts.append(dest)
            plan.append((it.repo_path(f), dest, f))

    print(f"repo: {repo_id}  ->  {root}")
    for it in items:
        print(f"  {it.kind:<12} {it.name}  {len(it.files)} files, {human(it.total_bytes())}"
              f"  -> {it.restore_to}")
    print(f"download: {len(plan)} files, {human(sum(f.bytes for *_, f in plan))}; "
          f"already present: {same}; would overwrite: {len(conflicts)}")
    if conflicts and not args.overwrite:
        for c in conflicts[:10]:
            print(f"  differs locally: {c}")
        raise UsageError(f"{len(conflicts)} local file(s) differ from the dataset; nothing was "
                         f"downloaded. Pass --overwrite to replace them.")
    if args.dry_run:
        print("dry run: nothing downloaded")
        return 0
    if not plan:
        print("everything already present")
        return 0

    staging = root / STAGING_DIR / repo_id.replace("/", "__")
    shutil.rmtree(staging, ignore_errors=True)
    staging.mkdir(parents=True)
    try:
        api.snapshot_download(repo_id, repo_type="dataset", revision=args.revision,
                              local_dir=str(staging), allow_patterns=[rp for rp, *_ in plan])
        for rp, _, f in plan:
            got = staging / rp
            if not got.is_file():
                raise UsageError(f"{rp} was not downloaded")
            if sha256_file(got) != f.sha256:
                raise UsageError(f"{rp}: SHA-256 does not match {MANIFEST_NAME}; nothing installed")
        for rp, dest, _ in plan:
            dest.parent.mkdir(parents=True, exist_ok=True)
            os.replace(staging / rp, dest)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
        try:
            (root / STAGING_DIR).rmdir()
        except OSError:
            pass
    print(f"installed {len(plan)} files (SHA-256 verified)")
    return 0


def _pull_raw(api: Any, repo_id: str, root: Path, args: argparse.Namespace) -> int:
    """A dataset not written by this tool: download it whole into one folder."""
    if args.item or args.kind:
        raise UsageError(f"{repo_id} has no {MANIFEST_NAME}, so --item/--kind cannot be used")
    dest = root / "source_documents" / f"hf_{repo_id.replace('/', '__')}"
    print(f"{repo_id} has no {MANIFEST_NAME} (not written by this tool); "
          f"downloading the whole repo to {dest}")
    if dest.exists() and any(dest.iterdir()) and not args.overwrite:
        raise UsageError(f"{dest} already exists; pass --overwrite to refresh it")
    if args.dry_run:
        print("dry run: nothing downloaded")
        return 0
    api.snapshot_download(repo_id, repo_type="dataset", revision=args.revision, local_dir=str(dest))
    shutil.rmtree(dest / ".cache", ignore_errors=True)
    print(f"downloaded to {dest}")
    return 0


