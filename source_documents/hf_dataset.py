@contextmanager
def prefer_ipv4() -> Iterator[None]:
    """Try IPv4 addresses before IPv6 for this process only.

    huggingface.co resolves to IPv6 (CloudFront) and IPv4 addresses. On networks
    where IPv6 routes are broken (seen on a ChromeOS/Crostini VM, 2026-11-12) the
    Hub client waits on the first IPv6 address without a connect timeout and the
    command hangs. Ordering IPv4 first fixes that; IPv6 stays as a fallback, so an
    IPv6-only network still works. Set HF_PREFER_IPV6=1 to keep the system order.
    """
    if os.environ.get("HF_PREFER_IPV6", "").strip() == "1":
        yield
        return
    original = socket.getaddrinfo

    def ordered(*args: Any, **kwargs: Any) -> list:
        res = original(*args, **kwargs)
        return sorted(res, key=lambda r: 0 if r[0] == socket.AF_INET else 1)

    socket.getaddrinfo = ordered
    try:
        yield
    finally:
        socket.getaddrinfo = original


COMMANDS = {"push": cmd_push, "list": cmd_list, "pull": cmd_pull, "whoami": cmd_whoami}


def main(argv: list[str] | None = None,
         api_factory: Callable[[str | None], Any] = make_api) -> int:
    args = build_parser().parse_args(argv)
    load_env()
    if not sys.stderr.isatty():  # logs/CI: the Hub's per-file progress bars are noise
        os.environ.setdefault("HF_HUB_DISABLE_PROGRESS_BARS", "1")
    try:
        with prefer_ipv4():
            return COMMANDS[args.command](args, api_factory)
    except UsageError as e:
        log(f"error: {e}")
        return 2
    except Exception as e:
        name = type(e).__name__
        if name in {"GatedRepoError", "RepositoryNotFoundError"} or \
                getattr(getattr(e, "response", None), "status_code", None) in (401, 403):
            log(f"error: access denied or repo not found ({name}). Check {TOKEN_ENV} has "
                f"access to this repo.")
            return 2
        log(f"error: {name}: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
